-- Add event receipt metadata, retry scheduling, leases, and immutable attempt history.
ALTER TABLE integration_events
    ADD COLUMN IF NOT EXISTS occurred_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS handler_key VARCHAR(100),
    ADD COLUMN IF NOT EXISTS correlation_id VARCHAR(255),
    ADD COLUMN IF NOT EXISTS processing_started_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS lease_expires_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS lease_owner VARCHAR(150),
    ADD COLUMN IF NOT EXISTS last_attempt_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS last_failed_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS next_attempt_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS error_code VARCHAR(100),
    ADD COLUMN IF NOT EXISTS failure_classification VARCHAR(30);
ALTER TABLE integration_events
    ADD COLUMN IF NOT EXISTS automatic_attempt_count INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS retry_requested_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS retry_reason VARCHAR(500);

UPDATE integration_events SET occurred_at = received_at WHERE occurred_at IS NULL;
UPDATE integration_events e SET handler_key = r.handler_key
FROM event_registry r WHERE e.handler_key IS NULL AND r.event_type=e.event_type;
ALTER TABLE integration_events ALTER COLUMN occurred_at SET NOT NULL;
UPDATE integration_events SET lease_expires_at = NOW()
WHERE status = 'processing' AND lease_expires_at IS NULL;

CREATE INDEX IF NOT EXISTS integration_events_due_idx
    ON integration_events (next_attempt_at, received_at, id)
    WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS integration_events_lease_idx
    ON integration_events (lease_expires_at)
    WHERE status = 'processing';
CREATE INDEX IF NOT EXISTS integration_events_correlation_idx
    ON integration_events (tenant_id, correlation_id);
CREATE INDEX IF NOT EXISTS integration_events_type_status_idx
    ON integration_events (tenant_id, event_type, status, received_at DESC);

CREATE TABLE IF NOT EXISTS integration_event_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    integration_event_id BIGINT NOT NULL REFERENCES integration_events(id) ON DELETE CASCADE,
    attempt_number INTEGER NOT NULL,
    worker_id VARCHAR(100) NOT NULL,
    correlation_id VARCHAR(255),
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ,
    outcome VARCHAR(30) NOT NULL DEFAULT 'started'
        CHECK (outcome IN ('started', 'processed', 'retry_scheduled', 'failed', 'lease_expired')),
    error_code VARCHAR(100),
    error_summary VARCHAR(500),
    failure_classification VARCHAR(30)
        CHECK (failure_classification IS NULL OR failure_classification IN ('transient', 'permanent', 'action_required')),
    retry_at TIMESTAMPTZ,
    initiated_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    retry_reason VARCHAR(500),
    UNIQUE (integration_event_id, attempt_number)
);

CREATE INDEX IF NOT EXISTS integration_event_attempts_event_idx
    ON integration_event_attempts (integration_event_id, attempt_number DESC);

CREATE TABLE IF NOT EXISTS integration_event_diagnostics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT,
    integrated_app_id BIGINT,
    request_id UUID,
    event_id VARCHAR(255),
    event_type VARCHAR(100),
    external_transaction_id VARCHAR(255),
    correlation_id VARCHAR(255),
    received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    outcome VARCHAR(30) NOT NULL
        CHECK (outcome IN ('unauthorized', 'invalid', 'duplicate', 'accepted', 'ingestion_failed')),
    error_code VARCHAR(100),
    error_summary VARCHAR(500),
    http_status SMALLINT NOT NULL,
    CONSTRAINT integration_event_diagnostics_app_fk
        FOREIGN KEY (tenant_id, integrated_app_id)
        REFERENCES integrated_apps (tenant_id, id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS integration_event_diagnostics_tenant_time_idx
    ON integration_event_diagnostics (tenant_id, received_at DESC);
CREATE INDEX IF NOT EXISTS integration_event_diagnostics_correlation_idx
    ON integration_event_diagnostics (tenant_id, correlation_id);
CREATE INDEX IF NOT EXISTS integration_event_diagnostics_external_tx_idx
    ON integration_event_diagnostics (tenant_id, external_transaction_id);
CREATE INDEX IF NOT EXISTS integration_event_diagnostics_event_idx
    ON integration_event_diagnostics (tenant_id, integrated_app_id, event_id, received_at DESC);
