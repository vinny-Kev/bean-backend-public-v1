-- The queue and domain tables already exist in the supplied application schema.
-- This adds the transactional outbox used by downstream analytics consumers.
CREATE TABLE IF NOT EXISTS analytics_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    source_event_id BIGINT NOT NULL REFERENCES integration_events(id) ON DELETE CASCADE,
    event_type VARCHAR(100) NOT NULL,
    payload JSONB NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'processing', 'processed', 'failed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    processed_at TIMESTAMPTZ,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    error_message TEXT,
    CONSTRAINT analytics_outbox_source_event_type_unique UNIQUE (source_event_id, event_type)
);

CREATE INDEX IF NOT EXISTS integration_events_pending_received_idx
    ON integration_events (received_at, id) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS analytics_outbox_pending_created_idx
    ON analytics_outbox (created_at, id) WHERE status = 'pending';
