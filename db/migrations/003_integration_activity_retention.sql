    IF fk_name IS NOT NULL THEN
        EXECUTE format('ALTER TABLE analytics_outbox DROP CONSTRAINT %I', fk_name);
    END IF;
END $$;
ALTER TABLE analytics_outbox ALTER COLUMN source_event_id DROP NOT NULL;
ALTER TABLE analytics_outbox ADD CONSTRAINT analytics_outbox_source_event_fk
    FOREIGN KEY (source_event_id) REFERENCES integration_events(id) ON DELETE SET NULL;
