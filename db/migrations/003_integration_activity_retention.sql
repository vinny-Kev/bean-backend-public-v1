WHERE st.source_event_id=e.id AND st.source_event_key IS NULL;

CREATE TABLE IF NOT EXISTS tenant_integration_settings (
    tenant_id BIGINT PRIMARY KEY REFERENCES tenants(id) ON DELETE CASCADE,
    inventory_shortage_policy VARCHAR(40) NOT NULL DEFAULT 'require_intervention'
        CHECK (inventory_shortage_policy IN (
            'require_intervention', 'allow_negative_inventory', 'record_sale_without_stock_deduction'
        )),
    updated_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS integration_lifecycle_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    integrated_app_id BIGINT NOT NULL,
    actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    action VARCHAR(100) NOT NULL,
    outcome VARCHAR(30) NOT NULL CHECK (outcome IN ('succeeded', 'failed')),
    correlation_id VARCHAR(255),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    error_code VARCHAR(100),
    error_summary VARCHAR(500),
    CONSTRAINT integration_lifecycle_activity_app_fk
        FOREIGN KEY (tenant_id, integrated_app_id)
        REFERENCES integrated_apps (tenant_id, id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS integration_lifecycle_activity_app_time_idx
    ON integration_lifecycle_activity (tenant_id, integrated_app_id, occurred_at DESC, id DESC);

-- Compact event-ID tombstones retain ingestion idempotency after source-event
-- payloads expire under the configurable source-event retention policy.
CREATE TABLE IF NOT EXISTS integration_event_deduplication (
    tenant_id BIGINT NOT NULL,
    integrated_app_id BIGINT NOT NULL,
    event_id VARCHAR(255) NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    external_transaction_id VARCHAR(255),
    correlation_id VARCHAR(255),
    first_received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (integrated_app_id, event_id),
    FOREIGN KEY (tenant_id, integrated_app_id)
        REFERENCES integrated_apps (tenant_id, id) ON DELETE CASCADE
);
INSERT INTO integration_event_deduplication
    (tenant_id, integrated_app_id, event_id, event_type, external_transaction_id, correlation_id, first_received_at)
SELECT e.tenant_id, e.integrated_app_id, e.event_id, e.event_type,
       e.payload->>'externalTransactionId', e.correlation_id, e.received_at
FROM integration_events e
ON CONFLICT (integrated_app_id, event_id) DO NOTHING;

-- Keep attempt history for its full retention period even after an old source
-- event is purged. Snapshot identifiers preserve traceability without payloads.
ALTER TABLE integration_event_attempts
    ADD COLUMN IF NOT EXISTS tenant_id BIGINT,
    ADD COLUMN IF NOT EXISTS integrated_app_id BIGINT,
    ADD COLUMN IF NOT EXISTS event_id VARCHAR(255),
    ADD COLUMN IF NOT EXISTS event_type VARCHAR(100),
    ADD COLUMN IF NOT EXISTS external_transaction_id VARCHAR(255);
UPDATE integration_event_attempts a
SET tenant_id=e.tenant_id,
    integrated_app_id=e.integrated_app_id,
    event_id=e.event_id,
    event_type=e.event_type,
    external_transaction_id=e.payload->>'externalTransactionId'
FROM integration_events e
WHERE a.integration_event_id=e.id AND a.tenant_id IS NULL;
DO $$
DECLARE fk_name TEXT;
BEGIN
    SELECT con.conname INTO fk_name
    FROM pg_constraint con
    WHERE con.conrelid='integration_event_attempts'::regclass
      AND con.confrelid='integration_events'::regclass AND con.contype='f'
    LIMIT 1;
    IF fk_name IS NOT NULL THEN
        EXECUTE format('ALTER TABLE integration_event_attempts DROP CONSTRAINT %I', fk_name);
    END IF;
END $$;
ALTER TABLE integration_event_attempts
    ALTER COLUMN integration_event_id DROP NOT NULL;
ALTER TABLE integration_event_attempts
    ADD CONSTRAINT integration_event_attempts_event_fk
    FOREIGN KEY (integration_event_id) REFERENCES integration_events(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS integration_event_attempts_retention_idx
    ON integration_event_attempts (finished_at, id);
CREATE INDEX IF NOT EXISTS integration_event_attempts_activity_idx
    ON integration_event_attempts (tenant_id, integrated_app_id, finished_at DESC, id DESC);

-- Outbox leases support a future destination dispatcher without claiming one exists.
ALTER TABLE analytics_outbox
    ADD COLUMN IF NOT EXISTS source_integration_id BIGINT,
    ADD COLUMN IF NOT EXISTS source_event_key VARCHAR(255),
    ADD COLUMN IF NOT EXISTS correlation_id VARCHAR(255),
    ADD COLUMN IF NOT EXISTS lease_owner VARCHAR(150),
    ADD COLUMN IF NOT EXISTS lease_expires_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS next_attempt_at TIMESTAMPTZ;
UPDATE analytics_outbox o
SET source_integration_id=e.integrated_app_id,
    source_event_key=e.event_id,
    correlation_id=e.correlation_id
FROM integration_events e
WHERE o.source_event_id=e.id AND o.source_event_key IS NULL;
