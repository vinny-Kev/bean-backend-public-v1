    ON analytics_outbox (source_integration_id, source_event_key, event_type)
    WHERE source_integration_id IS NOT NULL AND source_event_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS analytics_outbox_activity_idx
    ON analytics_outbox (tenant_id, source_integration_id, created_at DESC, id DESC);

